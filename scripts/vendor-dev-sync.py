#!/usr/bin/env python3
"""Extract the mobile-safe sync algorithms verbatim from a pinned Logseq dev commit.

Run with a local Logseq checkout, optionally --check. Platform adapters live in
scripts/vendor-dev-sync-platform.ml; changes to upstream algorithms belong in Logseq first.
"""
import argparse
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
REVISION = "53952776ef10805cba03009d444cf021f0d2c3ce"
PREFIX = "deps/db-worker/"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repository", type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    def source(path):
        return subprocess.check_output(
            ["git", "-C", str(args.repository), "show", f"{REVISION}:{PREFIX}{path}"], text=True)

    def definitions(path, names):
        text = source(path)
        chunks = []
        for name in names:
            start = re.search(rf"^let (?:rec )?{re.escape(name)}\b", text, re.M)
            if not start:
                raise ValueError(f"Missing {path}:{name}")
            end = re.search(r"^(?:let |type |module |exception )", text[start.end():], re.M)
            stop = start.end() + end.start() if end else len(text)
            chunks.append(text[start.start():stop].rstrip())
        return "\n\n".join(chunks) + "\n"

    def module(name, text):
        return f"module {name} = struct\n{text}\nend\n\n"

    output = f"(* Generated by scripts/vendor-dev-sync.py from logseq/logseq {REVISION}.\n   Upstream algorithms are copied verbatim; do not edit this file by hand.\n   License: shared/vendor/logseq-sync-LICENSE.md *)\n\n"
    output += module("Wire", source("spec/platform/wire.ml"))
    output += module("Transit_codec", source("runtime/native/transit_codec.ml"))
    output += module("Ds_wire", "open Datascript\n" + definitions("lib/ds_wire.ml", [
        "escape_string", "iso_of_ms", "edn_date", "edn_float", "edn_of_transit", "wire_int64",
        "transit_of_value", "value_of_transit", "entity_ref_of_transit", "datom_of_transit"]))
    output += module("Common_uuid", definitions("lib/common_uuid.ml", ["utf16_units"]))
    output += module("Db_normalize", source("lib/db_normalize.ml"))
    adapters = (ROOT / "scripts/vendor-dev-sync-platform.ml").read_text()
    output += adapters.split("(* TRANSact *)")[0]
    output += module("Db_transact", "open Datascript\n"
        + definitions("lib/db_transact.ml", ["kw", "tx_item_edn", "tx_edn", "entity_ref_of_wire",
            "unresolved_entity_ref", "entid_strict", "tx_ref_attr", "datom_form_tx_ops", "tx_ops_of_tx_data"])
        + adapters.split("(* TRANSact *)")[1].split("(* APPLY *)")[0])
    output += module("Common_defkeywords", source("lib/common_defkeywords.ml"))
    output += module("Kv_entity", source("lib/kv_entity.ml"))
    output += module("Sync_const", source("lib/sync_const.ml"))
    output += module("Sync_apply", "open Datascript\n"
        + definitions("lib/sync_apply.ml", ["reverse_data_ignored_attrs", "rtc_ignored_attrs",
            "remove_ignored_attrs", "normalize_tx_data", "reverse_tx_data", "normalize_tx_data_for_rebase",
            "ref_attr", "entity_of_wire_ref", "drop_cycle_parent_edges"]))
    output += adapters.split("(* APPLY *)")[1].split("(* REPLAY *)")[0]
    output += module("Sync_replay", "open Datascript\nopen Sync_apply\n"
        + definitions("lib/sync_replay.ml", ["resolve_temp_id", "tx_self_created",
            "unresolvable_uuid_ref", "pending_tx_unresolvable", "replay_pending_entry",
            "display_db_from_server", "display_db_rebind_floor"]))
    output += module("Db_sync_tx_sanitize", "open Datascript\n"
        + definitions("lib/db_sync_tx_sanitize.ml", ["entity_op_kinds", "encrypted_attrs", "vec_items",
            "drop_conflicted_encrypted_retracts"]))
    output = output.rstrip() + "\n"
    destination = ROOT / "shared/src/logseq/core/dev_sync.ml"
    license_text = subprocess.check_output(
        ["git", "-C", str(args.repository), "show", f"{REVISION}:LICENSE.md"], text=True)
    license_path = ROOT / "shared/vendor/logseq-sync-LICENSE.md"
    if args.check:
        if destination.read_text() != output or license_path.read_text() != license_text:
            raise SystemExit("Vendored sync differs from the pinned dev source")
        print(f"Verified dev sync source at {REVISION}")
    else:
        destination.write_text(output)
        license_path.parent.mkdir(parents=True, exist_ok=True)
        license_path.write_text(license_text)


if __name__ == "__main__":
    main()
