#!/usr/bin/env python3
"""Extract native-safe query algorithms from a pinned Logseq dev commit."""
import argparse
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
REVISION = "a63da5cb7993302f8c58ccf42eaf0083b77cf42b"
PREFIX = "deps/db-worker/"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repository", type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    def source(path):
        return subprocess.check_output(
            ["git", "-C", str(args.repository), "show", f"{REVISION}:{PREFIX}{path}"], text=True)

    def definitions(path, names):
        text = source(path)
        chunks = []
        for name in names:
            start = re.search(rf"^let (?:rec )?{re.escape(name)}\b", text, re.M)
            if not start:
                raise ValueError(f"Missing {path}:{name}")
            end = re.search(r"^(?:let |type |module |exception )", text[start.end():], re.M)
            stop = start.end() + end.start() if end else len(text)
            chunks.append(text[start.start():stop].rstrip())
        return "\n\n".join(chunks) + "\n"

    def module(name, text):
        return f"module {name} = struct\n{text}\nend\n\n"

    adapters = (ROOT / "scripts/vendor-dev-query-platform.ml").read_text()
    sections = re.split(r"\(\* SECTION: ([A-Z_]+) \*\)", adapters)
    parts = dict(zip(sections[1::2], sections[2::2]))
    output = f"(* Generated by scripts/vendor-dev-query.py from logseq/logseq {REVISION}.\n   Mobile adapters live in scripts/vendor-dev-query-platform.ml.\n   License: shared/vendor/logseq-query-LICENSE.md *)\n\n"
    output += '[@@@warning "-34"]\n\n'
    output += module("Wire", "include Dev_sync.Wire\nlet keyword s = Keyword s\n")
    output += module("Time", source("runtime/native/time.ml"))
    unicode = source("runtime/native/unicode.ml")
    output += module("Unicode", unicode[unicode.index("(* UTF-8 codec"):])
    output += module("Regexp", source("runtime/native/regexp.ml"))
    output += module("Ns_util", "let str_contains s sub = String_kit.includes ~sub s\n")
    output += module("Common_util", "open Datascript\n" + definitions("lib/common_util.ml", [
        "value_of_ms", "distinct_by", "parse_long", "js_string_of_float", "protect"]))
    output += module("Date_time_util", source("lib/date_time_util.ml"))
    output += module("Page_ref", source("lib/page_ref.ml"))
    output += parts["GRAPH"]
    output += module("Ds_wire", "open Datascript\ninclude Dev_sync.Ds_wire\n" + definitions("lib/ds_wire.ml", [
        "escape_string", "iso_of_ms", "edn_of_query_form"]))
    output += module("Edn_util", "open Datascript\nmodule Edn_parser = Melange_edn_native\n"
        + definitions("lib/edn_util.ml", ["value_of_edn", "read_string", "buffer_add_edn_escaped", "pr_str_to", "pr_str"]))
    output += module("Db_query_dsl", source("lib/db_query_dsl.ml"))
    output += module("Db_inputs", source("lib/db_inputs.ml"))
    output += parts["TRANSFORM"]
    output += module("Edn_eval", source("lib/edn_eval.ml").split("(* production wiring")[0])
    output += "open Datascript\n" + definitions("lib/render_resource.ml", [
        "form_of_wire", "value_of_form", "result_arg", "query_input_value", "resolve_page_ref_equality",
        "query_current_page_title", "resolve_custom_query_input", "add_query_rules", "execute_custom_query_typed"])
    destination = ROOT / "shared/src/logseq/core/dev_query.ml"
    license_text = subprocess.check_output(
        ["git", "-C", str(args.repository), "show", f"{REVISION}:LICENSE.md"], text=True)
    license_path = ROOT / "shared/vendor/logseq-query-LICENSE.md"
    output = output.rstrip() + "\n"
    if args.check:
        if destination.read_text() != output or license_path.read_text() != license_text:
            raise SystemExit("Vendored query differs from the pinned dev source")
        print(f"Verified dev query source at {REVISION}")
    else:
        destination.write_text(output)
        license_path.parent.mkdir(parents=True, exist_ok=True)
        license_path.write_text(license_text)


if __name__ == "__main__":
    main()
