#!/usr/bin/env python3
"""Generate Android vectors from the canonical iOS/master icon assets."""
from pathlib import Path
import json
import math
import xml.etree.ElementTree as ET

repo = Path(__file__).resolve().parent.parent
assets = repo / 'apple/Sources/Logseq/Resources/Icons.xcassets'
names = ['task_backlog', 'task_todo', 'task_doing', 'task_review', 'task_done',
         'task_canceled', 'priority_urgent', 'priority_high', 'priority_medium',
         'priority_low', 'outliner_bullet', 'outliner_bullet_closed']

def path_data(node, attrs):
    kind = node.tag.rsplit('}', 1)[-1]
    if kind == 'path':
        return node.attrib['d']
    if kind == 'circle':
        x, y, r = (float(attrs[k]) for k in ('cx', 'cy', 'r'))
        if 'stroke-dasharray' in attrs:
            length = 2 * math.pi * r
            parts = []
            for start in range(0, math.ceil(length), 8):
                a, b = start / r, min(start + 4, length) / r
                parts.append(f'M{x+r*math.cos(a):.6f} {y+r*math.sin(a):.6f} A{r} {r} 0 0 1 {x+r*math.cos(b):.6f} {y+r*math.sin(b):.6f}')
            return ' '.join(parts)
        return f'M{x+r} {y} A{r} {r} 0 1 0 {x-r} {y} A{r} {r} 0 1 0 {x+r} {y} Z'
    if kind == 'rect':
        x, y, w, h = (float(attrs[k]) for k in ('x', 'y', 'width', 'height'))
        r = float(attrs.get('rx', 0))
        return f'M{x+r} {y} H{x+w-r} Q{x+w} {y} {x+w} {y+r} V{y+h-r} Q{x+w} {y+h} {x+w-r} {y+h} H{x+r} Q{x} {y+h} {x} {y+h-r} V{y+r} Q{x} {y} {x+r} {y} Z'
    raise ValueError(kind)

lines = ['// Generated by scripts/generate-android-master-icons.py. Do not edit.',
         'package com.logseq.app.runtime', '',
         'import androidx.compose.ui.graphics.Color',
         'import androidx.compose.ui.graphics.PathFillType',
         'import androidx.compose.ui.graphics.SolidColor',
         'import androidx.compose.ui.graphics.StrokeCap',
         'import androidx.compose.ui.graphics.StrokeJoin',
         'import androidx.compose.ui.graphics.vector.ImageVector',
         'import androidx.compose.ui.graphics.vector.PathParser',
         'import androidx.compose.ui.unit.dp', '',
         'internal val masterIcons: Map<String, ImageVector> = mapOf(']
for name in names:
    root = ET.parse(next((assets / (name + '.imageset')).glob('*.svg'))).getroot()
    _, _, width, height = map(float, root.attrib['viewBox'].split())
    lines += [f'    "{name.replace("_", "-")}" to ImageVector.Builder(',
              f'        name = "{name}", defaultWidth = 24.dp, defaultHeight = 24.dp,',
              f'        viewportWidth = {width}f, viewportHeight = {height}f,', '    ).apply {']
    def emit(node, inherited):
        attrs = inherited | node.attrib
        if node.tag.rsplit('}', 1)[-1] in ('svg', 'g'):
            for child in node:
                emit(child, attrs)
            return
        data = path_data(node, attrs)
        fill = 'null' if attrs.get('fill') == 'none' else 'SolidColor(Color.Black)'
        stroke = 'SolidColor(Color.Black)' if attrs.get('stroke', 'none') != 'none' else 'null'
        opacity = float(attrs.get('opacity', 1))
        cap = 'Round' if attrs.get('stroke-linecap') == 'round' else 'Butt'
        join = 'Round' if attrs.get('stroke-linejoin') == 'round' else 'Miter'
        fill_type = 'EvenOdd' if attrs.get('fill-rule') == 'evenodd' else 'NonZero'
        lines.extend(['        addPath(',
            f'            pathData = PathParser().parsePathString({json.dumps(data)}).toNodes(),',
            f'            fill = {fill}, fillAlpha = {opacity}f,',
            f'            stroke = {stroke}, strokeAlpha = {opacity}f, strokeLineWidth = {float(attrs.get("stroke-width", 1))}f,',
            f'            strokeLineCap = StrokeCap.{cap}, strokeLineJoin = StrokeJoin.{join}, pathFillType = PathFillType.{fill_type},',
            '        )'])
    emit(root, {})
    lines += ['    }.build(),']
lines += [')', '']
(repo / 'android/app/src/main/kotlin/com/logseq/app/runtime/MasterIcons.kt').write_text('\n'.join(lines))
