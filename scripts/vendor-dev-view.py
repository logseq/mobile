#!/usr/bin/env python3
"""Extract native view filtering and sorting from a pinned Logseq worker."""
import argparse
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
REVISION = "a7191d3d9deba5e34a6fb51d6454ed1d7e680965"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repository", type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    def source(path):
        return subprocess.check_output(
            ["git", "-C", str(args.repository), "show", f"{REVISION}:deps/db-worker/{path}"], text=True)

    def definition(text, name):
        start = re.search(rf"^let (?:rec )?{re.escape(name)}\b", text, re.M)
        if not start:
            raise ValueError(f"Missing definition: {name}")
        end = re.search(r"^(?:let |type |module |exception )", text[start.end():], re.M)
        stop = start.end() + end.start() if end else len(text)
        return text[start.start():stop].rstrip() + "\n\n"

    text = source("lib/db_view.ml")
    output = f"(* Generated by scripts/vendor-dev-view.py from logseq/logseq {REVISION}.\n   License: shared/vendor/logseq-query-LICENSE.md *)\n\n"
    output += "module Time = Dev_query.Time\nmodule Unicode = Dev_query.Unicode\nmodule Date_time_util = Dev_query.Date_time_util\n"
    output += "module Common_util = struct\n"
    common = source("lib/common_util.ml")
    for name in ["js_string_of_float", "js_number_of_string"]:
        output += definition(common, name)
    output += "end\n\n"
    output += (ROOT / "scripts/vendor-dev-view-platform.ml").read_text() + "\n"
    output += "open Datascript\nmodule Int_set = Set.Make(Int)\n\n"
    for name in ["contains_substring", "dedupe_ids", "entid", "get_block_alias_ids",
                 "hidden_eid_pred", "hidden_ref_id_pred_with", "hidden_ref_id_pred",
                 "get_block_refs_count", "get_property_value_content", "str_of_value"]:
        output += definition(text, name)
    output += definition(source("lib/db_class.ml"), "property_object_eids")
    output += text[text.index("let get_timestamp "):text.index("let avet_first_window_sort_attrs")]
    output += definition(text, "sort_eids_by_sorting")
    output += text[text.index("let empty_attr_values "):text.index("let get_feature_row_data ")]
    destination = ROOT / "shared/src/logseq/core/dev_view.ml"
    if args.check:
        if destination.read_text() != output:
            raise SystemExit("Vendored views differ from the pinned worker source")
        print(f"Verified native view source at {REVISION}")
    else:
        destination.write_text(output)


if __name__ == "__main__":
    main()
