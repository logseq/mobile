(* datalog-clause? *)
let is_datalog_clause (e : query_form) : bool =
  is_coll e
  && (match first_elem e with
      | Some f when is_list f -> true
      | Some (QueryFormSymbol s) ->
          List.length (coll_elems e) >= 2
          && String.length s > 0 && s.[0] = '?'
      | _ -> false)

let rec build_query (e : query_form) (env : env) (level : int)
    (current_filter : string option) : built option =
  let fe : query_form option =
    match first_elem e with
    | Some f -> Some f
    | None ->
        (* cljs (first "abc") -> "a" char; on non-coll e first is nil *)
        (match e with
         | QueryFormString s when String.length s > 0 -> Some (str (String.make 1 s.[0]))
         | _ -> None)
  in
  let fe_name =
    match fe with
    | Some f when is_list f -> None (* list fe stays a form *)
    | Some (QueryFormSymbol s) -> Some (Unicode.lowercase (name_of_form (sym s)))
    | Some (QueryFormKeyword s) -> Some (Unicode.lowercase (name_of_form (kw s)))
    | Some other ->
        (match other with
         | QueryFormString s -> Some (Unicode.lowercase s)
         | f -> Some (Unicode.lowercase (Ds_wire.edn_of_query_form f)))
    | None -> None
  in
  let fe_sym name = fe_name = Some name && (match fe with Some (QueryFormSymbol _ | QueryFormKeyword _) -> true | _ -> false) in
  let page_ref =
    match e with QueryFormString s -> Page_ref.is_page_ref s | _ -> false
  in
  if
    List.exists
      (fun op -> fe_sym op)
      [ "between"; "property"; "private-property"; "todo"; "task"; "priority"; "page" ]
    || ((not page_ref) && match e with QueryFormString _ -> true | _ -> false)
  then env.blocks <- true;
  if match e with QueryFormNil -> true | _ -> false then None
  else if is_datalog_clause e then Some { bquery = vec_ [ e ]; brules = [] }
  else if
    fe_sym "and"
    && List.for_all
         (fun f -> match f with QueryFormString s -> Page_ref.is_page_ref s | _ -> false)
         (match coll_elems e with _ :: rest -> rest | _ -> [])
  then
    (* (and [[a]] [[b]]) -> (and [[a]] [[b]] (or [[a]] [[b]])) *)
    let rest = match coll_elems e with _ :: r -> r | _ -> [] in
    let e' = list_ (coll_elems e @ [ list_ (sym "or" :: rest) ]) in
    build_query e' env level current_filter
  else if page_ref then
    if current_filter = Some "or" || form_equal env.form e then
      build_page_ref_or_self_ref env.db e true
    else build_page_ref_or_self_ref env.db e false
  else
    match e with
    | QueryFormString _ -> Some (build_block_content e)
    | _ when fe_sym "and" || fe_sym "or" || fe_sym "not" ->
        build_and_or_not env level e (Option.get fe_name) current_filter
    | _ when fe_sym "between" -> build_between e
    | _ when fe_sym "property" -> build_property env.db e env
    | _ when fe_sym "private-property" ->
        build_property env.db e { env with private_property = true }
    | _ when fe_sym "todo" || fe_sym "task" -> build_task e
    | _ when fe_sym "priority" -> build_priority e
    | _ when fe_sym "page" -> build_page e
    | _ when fe_sym "sample" -> build_sample e env
    | _ when fe_sym "tags" -> build_tags env.db e
    | _ -> None

and build_and_or_not (env : env) (level : int) (e : query_form) (fe : string)
    (current_filter : string option) : built option =
  let raw_clauses =
    List.filter_map
      (fun form -> build_query form env (level + 1) (Some fe))
      (match coll_elems e with _ :: r -> r | _ -> [])
  in
  let clauses =
    raw_clauses
    |> List.map (fun b -> b.bquery)
    |> List.filter (fun q -> not (match q with QueryFormNil -> true | _ -> false))
    |> distinct_preserve_order
  in
  let clauses =
    if fe = "and" then
      let nots, others = List.partition not_clause clauses in
      others @ nots
    else clauses
  in
  let nested_and = fe = "and" && current_filter = Some "and" in
  match clauses with
  | [] -> None
  | _ ->
      let result = build_and_or_not_result fe clauses current_filter nested_and in
      List.iter (fun v -> Hashtbl.replace env.vars v ()) (collect_vars result);
      let query =
        if nested_and then result
        else if level = 0 && (fe = "and" || fe = "or") then result
        else if fe = "not" && Option.is_some current_filter then result
        else vec_ [ result ]
      in
      Some
        { bquery = query;
          brules =
            Common_util.distinct_by Fun.id
              (List.concat_map (fun b -> b.brules) raw_clauses) }

(* ============ parse ============ *)

(* collect-vars-by-polarity — vars inside (not ...) count as negative *)
let collect_vars_by_polarity (form : query_form) : string list * string list =
  let pos = Hashtbl.create 8 and neg = Hashtbl.create 8 in
  let rec walk x positive =
    match x with
    | QueryFormSymbol s when String.length s > 0 && s.[0] = '?' ->
        Hashtbl.replace (if positive then pos else neg) s ()
    | QueryFormList (QueryFormSymbol "not" :: rest) ->
        List.iter (fun c -> walk c false) rest
    | QueryFormVector xs | QueryFormList xs | QueryFormSet xs ->
        List.iter (fun c -> walk c positive) xs
    | QueryFormMap kvs ->
        List.iter (fun (k, v) -> walk k positive; walk v positive) kvs
    | _ -> ()
  in
  walk form true;
  ( Hashtbl.fold (fun k () acc -> k :: acc) pos [],
    Hashtbl.fold (fun k () acc -> k :: acc) neg [] )

(* add-bindings! — prepend domain-establishing clauses for vars that
   only appear negatively *)
let add_bindings (q : query_form list) : query_form list =
  let pos, neg =
    List.fold_left
      (fun (p, n) clause ->
        let p', n' = collect_vars_by_polarity clause in
        (p @ p', n @ n'))
      ([], []) q
  in
  let pos = List.sort_uniq compare pos and neg = List.sort_uniq compare neg in
  let appears v = List.mem v pos || List.mem v neg in
  let needs_domain v = appears v && not (List.mem v pos) in
  let b_need = needs_domain "?b" and p_need = needs_domain "?p" in
  let bindings =
    if b_need && p_need then [ [ vec_ [ sym "?b"; kw "block/page"; sym "?p" ] ] ]
    else if b_need then
      [ [ vec_ [ sym "?b"; kw "block/uuid" ];
          vec_ [ list_ [ sym "missing?"; sym "$"; sym "?b"; kw "logseq.property/built-in?" ] ] ] ]
    else if p_need then [ [ vec_ [ sym "?p"; kw "block/name" ] ] ]
    else if List.mem "?b" pos && List.mem "?p" pos then
      [ [ vec_ [ sym "?b"; kw "block/page"; sym "?p" ] ] ]
    else []
  in
  List.concat bindings @ q

type parsed =
  { pquery : query_form list option
  ; prules : query_form list
  ; prule_names : string list
  ; pblocks : bool
  ; psample : int option
  }

(* query-dsl/parse *)
let parse ?(cards : bool = false) (db : db) (s : string) : parsed option =
  ignore cards;
  if Unicode.trim s = "" then None
  else
    let s =
      if String.length s > 0 && s.[0] = '#' then
        Page_ref.to_page_ref (String.sub s 1 (String.length s - 1))
      else s
    in
    (* cljs (reader/read-string custom-readers) — malformed EDN throws *)
    let form =
      simplify_query (apply_custom_readers (Parser.read_edn (pre_transform s)))
    in
    let env =
      { db; form; blocks = false;
        sample = None; vars = Hashtbl.create 8; private_property = false }
    in
    (* cljs (when form (build-query form {:form form ...})) *)
    let built =
      match form with
      | QueryFormNil -> None
      | f -> build_query f env 0 None
    in
    let result =
      match built with
      | Some { bquery = q; _ } -> (match coll_elems q with [] -> None | elems -> Some (q, elems))
      | None -> None
    in
    let result' =
      match result with
      | None -> None
      | Some (q, elems) ->
          (* key = keyword of first element of first element when it is a
             coll, else keyword of the first element *)
          let key =
            match elems with
            | first :: _ when is_coll first ->
                (match first_elem first with
                 | Some (QueryFormSymbol s) -> s
                 | Some (QueryFormKeyword s) -> s
                 | _ -> "")
            | QueryFormSymbol s :: _ -> s
            | QueryFormKeyword k :: _ -> k
            | _ -> ""
          in
          if key = "and" then
            (* (and c1 c2 ...) -> (c1 c2 ...) *)
            (match q with
             | QueryFormList (_ :: clauses) -> Some clauses
             | _ -> Some elems)
          else Some (coll_elems q)
    in
    let result' = Option.map add_bindings result' in
    let rule_names =
      match built with
      | Some b ->
          let rules = List.sort_uniq compare b.brules in
          if List.mem "page-ref" rules then List.sort_uniq compare ("self-ref" :: rules)
          else rules
      | None -> []
    in
    Some
      { pquery = result'
      ; prules = extract_rules rule_names
      ; prule_names = rule_names
      ; pblocks = env.blocks
      ; psample = env.sample
      }

let parse_query ?(cards : bool = false) db s options =
  ignore cards;
  let current_page_title, today_day = options in
  parse ~cards db (resolve_dynamic_template s ~current_page_title ~today_day)

(* ============ query wrapper + execution ============ *)

(* query-dsl/query-wrapper — where is the clause list produced by parse *)
let query_wrapper (where : query_form list) ~blocks ~block_attrs_edn : string =
  let attrs =
    match block_attrs_edn with
    | Some e -> (match try Some (Parser.read_edn e) with _ -> None with Some f -> f | None -> vec_ [ sym "*" ])
    | None -> vec_ [ sym "*" ]
  in
  let find =
    if blocks then
      [ kw "find"; list_ [ sym "pull"; sym "?b"; attrs ]; kw "in"; sym "$"; sym "%"; kw "where" ]
    else
      [ kw "find"; list_ [ sym "pull"; sym "?p"; vec_ [ sym "*" ] ]; kw "in"; sym "$"; sym "%"; kw "where" ]
  in
  let elems =
    match where with
    | first :: _ when is_coll first -> find @ where
    | _ -> find @ [ list_ where ]
  in
  Ds_wire.edn_of_query_form (vec_ elems)

let with_raw_title (r : query_result) : query_result =
  match r with
  | Result_pull p ->
      let has k = List.exists (fun (key, _) -> key = Keyword k) p.pulled_attrs in
      if has "block/title" && not (has "block/raw-title") then
        let title_v = List.assoc (Keyword "block/title") p.pulled_attrs in
        Result_pull
          { p with pulled_attrs = p.pulled_attrs @ [ (Keyword "block/raw-title", title_v) ] }
      else r
  | _ -> r

let query_result_tuples (rows : query_result list list) : query_result list list =
  List.map (List.map with_raw_title) rows

let sample_results (rows : query_result list list) (sample : int option) : query_result list list =
  match sample with
  | Some n when n > 0 && List.length rows > n ->
      let arr = Array.of_list rows in
      for i = Array.length arr - 1 downto 1 do
        let j = Random.int (i + 1) in
        let tmp = arr.(i) in
        arr.(i) <- arr.(j);
        arr.(j) <- tmp
      done;
      Array.to_list (Array.sub arr 0 n)
  | _ -> rows

type exec_opts =
  { opt_cards : bool
  ; opt_block_attrs : string option
  ; opt_current_page_title : string option
  ; opt_today_day : Time.local_date option
  }

let () = Random.self_init ()

(* query-dsl/execute-query *)
let execute_query (db : db) (query_string : string) (opts : exec_opts) : query_result list list option =
  if String.length query_string > 0 && query_string <> "\"\"" then
    match
      parse_query db query_string
        (opts.opt_current_page_title, opts.opt_today_day)
    with
    | Some { pquery = Some query_star; prules; psample; _ } ->
        let query_star =
          if opts.opt_cards then
            (* cljs card-class-ids: Card + every structured child (tags that
               extend Card), matched via a contains? set predicate *)
            let card_ids =
              match entity db (Ident "logseq.class/Card") with
              | Some e -> e.id :: Db_class.get_structured_children db e.id
              | None -> []
            in
            let clauses =
              match query_star with
              | first :: _ when is_coll first -> query_star
              | _ -> [ list_ query_star ]
            in
            vec_ [ sym "?b"; kw "block/tags"; sym "?t" ]
            :: vec_
                 [ list_
                     [ sym "contains?"
                     ; QueryFormSet (List.map int card_ids)
                     ; sym "?t" ] ]
            :: clauses
          else query_star
        in
        let q' = query_wrapper query_star ~blocks:true ~block_attrs_edn:opts.opt_block_attrs in
        let rows = Datascript.q_string db q' ~inputs:[ parse_rules_input prules ] in
        Some (sample_results (query_result_tuples rows) psample)
    | _ -> None
  else None

(* query-dsl/execute-custom-query — :query is a DSL form (list), not a
   string. cljs does (resolve-dynamic-template (pr-str (:query m)) {}). *)
let execute_custom_query (db : db) (query_form_edn : string) (opts : exec_opts) : query_result list list option =
  (* query_form_edn = pr-str of (:query query-m); empty -> nil like cljs (seq (:query m)) *)
  let s = resolve_dynamic_template query_form_edn ~current_page_title:None ~today_day:None in
  match parse db s with
  | Some { pquery = Some query_star; prules; pblocks; _ } ->
      let q' = query_wrapper query_star ~blocks:pblocks ~block_attrs_edn:opts.opt_block_attrs in
      Some (query_result_tuples (Datascript.q_string db q' ~inputs:[ parse_rules_input prules ]))
  | _ -> None

end

module Db_inputs = struct
(* Faithful port of logseq.db.frontend.inputs
   (deps/db/src/logseq/db/frontend/inputs.cljs): resolves the special
   :inputs keywords (:current-page, :query-page, :current-block,
   :parent-block, :today/:yesterday/:tomorrow, :right-now-ms), relative
   dates (:+7d, :-1w, ...), time-suffixed dates (:today-0230,
   :+7d-0230, :1d-before-ms ...), and [[page-ref]] string inputs into
   concrete query input values. *)

open Datascript

(* cljs opts map: {:keys [current-block-uuid current-page-fn]} *)
type context =
  { current_block_uuid : string option
  ; current_page_fn : unit -> string option
  }

let kw_name (k : string) : string =
  match String.index_opt k '/' with
  | Some i -> String.sub k (i + 1) (String.length k - i - 1)
  | None -> k

let kw_namespace (k : string) : string option =
  match String.index_opt k '/' with
  | Some i -> Some (String.sub k 0 i)
  | None -> None

let is_digit c = c >= '0' && c <= '9'

(* Split "+7d" into (direction, amount, unit); unit "" when absent.
   For inputs like "+7d-ms"/"-3w-start" also returns the trailing
   "-ms"/"-start"/"-0230" part. *)
let split_offset (name : string) : (string * int * string * string option) option =
  let n = String.length name in
  if n < 2 || (name.[0] <> '+' && name.[0] <> '-') then None
  else
    let direction = String.sub name 0 1 in
    let i = ref 1 in
    while !i < n && is_digit name.[!i] do
      incr i
    done;
    if !i = 1 || !i >= n then None
    else
      let amount = int_of_string (String.sub name 1 (!i - 1)) in
      let unit = String.sub name !i 1 in
      if not (String.contains "dwmy" unit.[0]) then None
      else if !i + 1 = n then Some (direction, amount, unit, None)
      else Some (direction, amount, unit, Some (String.sub name (!i + 1) (n - !i - 1)))

(* keyword-input-dispatch — cljs re-find equivalents, hand-implemented
   (the Regexp platform vm only supports first-match). *)

(* #"^[+-]\d+[dwmy]?$" *)
let match_relative_date (name : string) : bool =
  match split_offset name with
  | Some (_, _, _, None) -> true
  | _ -> false

(* #"^[+-]\d+[dwmy]-(ms|start|end|\d{2}|\d{4}|\d{6}|\d{9})?$" *)
let match_relative_date_time (name : string) : bool =
  match split_offset name with
  | Some (_, _, _, Some suffix) ->
      let suffix = String.sub suffix 1 (String.length suffix - 1) in
      (* suffix after the '-' *)
      (* cljs dispatch regex allows an empty optional group after the
         '-', but the resolve re-find requires a non-empty ts, so "+7d-"
         is dispatched then resolves to nil (unresolved). *)
      if suffix = "ms" || suffix = "start" || suffix = "end" then true
      else
        let l = String.length suffix in
        (l = 2 || l = 4 || l = 6 || l = 9)
        && (let rec digits i = i >= l || (is_digit suffix.[i] && digits (i + 1)) in
            digits 0)
  | _ -> false

(* #"^today-(start|end|\d{2}|\d{4}|\d{6}|\d{9})$" *)
let match_today_time (name : string) : bool =
  if String.length name > 6 && String.sub name 0 6 = "today-" then
    let suffix = String.sub name 6 (String.length name - 6) in
    if suffix = "start" || suffix = "end" then true
    else
      let l = String.length suffix in
      (l = 2 || l = 4 || l = 6 || l = 9)
      && (let rec digits i = i >= l || (is_digit suffix.[i] && digits (i + 1)) in
          digits 0)
  else false

(* #"^\d+d(-before|-after|-before-ms|-after-ms)?$" *)
let match_deprecated (name : string) : bool =
  let n = String.length name in
  let i = ref 0 in
  while !i < n && is_digit name.[!i] do
    incr i
  done;
  !i > 0
  && !i < n
  && name.[!i] = 'd'
  && (let rest = String.sub name (!i + 1) (n - !i - 1) in
      rest = "" || rest = "-before" || rest = "-after" || rest = "-before-ms"
      || rest = "-after-ms")

type dispatch =
  | Fixed
  | Relative_date
  | Relative_date_time
  | Today_time
  | Deprecated_relative_date
  | Unresolved

let dispatch (k : string) : dispatch =
  match k with
  | "current-page" | "query-page" | "current-block" | "parent-block"
  | "today" | "yesterday" | "tomorrow" | "right-now-ms" ->
      Fixed
  | _ ->
      let name = kw_name k in
      if match_relative_date name then Relative_date
      else if match_relative_date_time name then Relative_date_time
      else if k = "start-of-today-ms" || k = "end-of-today-ms" || match_today_time name
      then Today_time
      else if match_deprecated name then Deprecated_relative_date
      else Unresolved

let ends_with s suffix =
  let n = String.length s and l = String.length suffix in
  n >= l && String.sub s (n - l) l = suffix

let contains_sub s sub =
  let n = String.length s and l = String.length sub in
  let rec find i =
    if i + l > n then false
    else if String.sub s i l = sub then true
    else find (i + 1)
  in
  l > 0 && find 0

(* old->new-relative-date-format: :1d-before -> :today/-1d,
   :1d-after-ms -> :today/+1d-ms *)
let old_to_new_relative_date_format (k : string) : string =
  let name = kw_name k in
  let i = ref 0 in
  while !i < String.length name && is_digit name.[!i] do
    incr i
  done;
  let count' = String.sub name 0 !i in
  let plus_minus = if contains_sub name "after" then "+" else "-" in
  let ms = if ends_with name "-ms" then "-ms" else "" in
  "today/" ^ plus_minus ^ count' ^ "d" ^ ms

(* get-relative-date — only the "today" namespace is supported in cljs *)
let get_relative_date (k : string) : int64 =
  match kw_namespace k with
  | None | Some "today" -> Date_time_util.today_ms ()
  | Some ns -> invalid_arg ("unsupported date namespace: " ^ ns)

(* get-offset-date *)
let get_offset_date (relative_to : int64) (direction : string) (amount : int)
    (unit : string) : int64 =
  let p =
    match unit with
    | "d" -> Date_time_util.Days
    | "w" -> Date_time_util.Weeks
    | "m" -> Date_time_util.Months
    | "y" -> Date_time_util.Years
    | _ -> invalid_arg ("unsupported offset unit: " ^ unit)
  in
  match direction with
  | "+" -> Date_time_util.plus p amount relative_to
  | "-" -> Date_time_util.minus p amount relative_to
  | _ -> invalid_arg ("unsupported offset direction: " ^ direction)

(* get-ts-units — offset-time is the raw suffix string ("ms", "start",
   "end", or HHMM[SS[mmm]] digits). *)
let get_ts_units (offset_direction : string) (offset_time : string) :
    int * int * int * int =
  match offset_time with
  | "ms" ->
      if offset_direction = "+" then (23, 59, 59, 999) else (0, 0, 0, 0)
  | "start" -> (0, 0, 0, 0)
  | "end" -> (23, 59, 59, 999)
  | _ ->
      let t = offset_time ^ "000000000" in
      let pair i = int_of_string (String.sub t i 2) in
      (min 23 (pair 0), min 59 (pair 2), min 59 (pair 4),
       min 999 (int_of_string (String.sub t 6 3)))

let current_block_ent (db : db) (ctx : context) : entity option =
  match ctx.current_block_uuid with
  | Some uuid -> entity db (Lookup_ref ("block/uuid", Uuid uuid))
  | None -> None

(* resolve-keyword-input — returns None for the cljs nil cases;
   resolve-input falls back to the unresolved input. *)
let rec resolve_keyword_input (db : db) (k : string) (ctx : context) :
    value option =
  match dispatch k with
  | Fixed ->
      (match k with
       | "current-page" ->
           (match ctx.current_page_fn () with
            | Some title -> Some (String (Unicode.lowercase title))
            | None -> None)
       | "query-page" ->
           (match current_block_ent db ctx with
            | Some block ->
                (match Entity_refs.ref_ent block "block/page" with
                 | Some page -> Ldb.value page "block/name"
                 | None -> None)
            | None -> None)
       | "current-block" ->
           Option.map (fun (e : entity) -> Int64 (Int64.of_int e.id)) (current_block_ent db ctx)
       | "parent-block" ->
           (match current_block_ent db ctx with
            | Some block ->
                Option.map (fun (p : entity) -> Int64 (Int64.of_int p.id))
                  (Entity_refs.ref_ent block "block/parent")
            | None -> None)
       | "today" ->
           Some
             (Int64
                (Int64.of_int
                   (Date_time_util.date_to_int (Date_time_util.today_ms ()))))
       | "yesterday" ->
           Some
             (Int64
                (Int64.of_int
                   (Date_time_util.date_to_int
                    (Date_time_util.minus Days 1 (Date_time_util.today_ms ())))))
       | "tomorrow" ->
           Some
             (Int64
                (Int64.of_int
                   (Date_time_util.date_to_int
                    (Date_time_util.plus Days 1 (Date_time_util.today_ms ())))))
       | "right-now-ms" ->
           Some (Common_util.value_of_ms (Date_time_util.time_ms ()))
       | _ -> None)
  | Today_time ->
      let hh, mm, ss, ms =
        match k with
        | "start-of-today-ms" -> (0, 0, 0, 0)
        | "end-of-today-ms" -> (23, 59, 59, 999)
        | _ -> get_ts_units "" (String.sub (kw_name k) 6 (String.length (kw_name k) - 6))
      in
      Some
        (Common_util.value_of_ms
           (Date_time_util.date_at_local_ms
              (Date_time_util.today_ms ()) hh mm ss ms))
  | Relative_date ->
      let name = kw_name k in
      let relative_to = get_relative_date k in
      (match split_offset name with
       | Some (direction, amount, unit, None) ->
           let offset_date = get_offset_date relative_to direction amount unit in
           Some (Int64 (Int64.of_int (Date_time_util.date_to_int offset_date)))
       | _ -> invalid_arg ("invalid relative date input: " ^ k))
  | Relative_date_time ->
      let name = kw_name k in
      let relative_to = get_relative_date k in
      (match split_offset name with
       | Some (direction, amount, unit, Some suffix) when suffix <> "" ->
           let ts = String.sub suffix 1 (String.length suffix - 1) in
           let offset_date =
             get_offset_date relative_to direction amount unit
           in
           let hh, mm, ss, ms = get_ts_units direction ts in
           Some
             (Common_util.value_of_ms
                (Date_time_util.date_at_local_ms offset_date hh mm ss ms))
       | _ -> invalid_arg ("invalid relative date-time input: " ^ k))
  | Deprecated_relative_date ->
      resolve_keyword_input db (old_to_new_relative_date_format k) ctx
  | Unresolved -> None

(* resolve-input *)
let resolve_input (db : db) (input : value) (ctx : context) : value =
  match input with
  | Keyword k ->
      (match resolve_keyword_input db k ctx with
       | Some v -> v
       | None -> input)
  | String s when Page_ref.is_page_ref s ->
      (match Page_ref.get_page_name s with
       | Some name -> String (Unicode.lowercase name)
       | None -> input)
  | _ -> input

end


