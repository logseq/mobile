  | QueryFormTagged (tag, rep) -> "#" ^ tag ^ " " ^ edn_of_query_form rep
  | QueryFormMap kvs ->
      let pair (k, v) = edn_of_query_form k ^ " " ^ edn_of_query_form v in
      "{" ^ String.concat " " (List.map pair kvs) ^ "}"

