module Time = struct
(* Time spec implementation for the native target.

   epoch_ms is int64. tz distinguishes the system local zone — resolved
   through Unix.localtime/mktime so DST transitions stay correct — from
   fixed offsets, which use pure civil<->days arithmetic plus the minute
   offset (no tz database needed). *)

type epoch_ms = int64
type monotonic_ms = float
type tz = Local_tz | Offset_tz of int (* minutes east of UTC *)
type local_date = { ld_year : int; ld_month : int; ld_day : int; ld_tz : tz }
type civil =
  { cv_year : int
  ; cv_month : int
  ; cv_day : int
  ; cv_hour : int
  ; cv_minute : int
  ; cv_second : int
  ; cv_ms : int
  }

(* ---- timezones ---- *)

let local_tz () = Local_tz
let utc = Offset_tz 0
let tz_of_offset_minutes n = Offset_tz n
let equal_tz a b = a = b

(* ---- epoch_ms ---- *)

let epoch_ms (n : int64) = n
let epoch_ms_of_float f = Int64.of_float f
let epoch_ms_to_int64 t = t
let epoch_ms_to_float t = Int64.to_float t
let compare_epoch_ms = Int64.compare
let now () = Int64.of_float (Unix.gettimeofday () *. 1000.)

(* ---- monotonic_ms ---- *)

let monotonic_now () = Unix.gettimeofday () *. 1000.
let diff_monotonic_ms a b = b -. a
let compare_monotonic_ms = Float.compare

(* ---- int64 floor division + civil<->days (Howard Hinnant) ---- *)

let floor_div64 a b =
  let q = Int64.div a b and r = Int64.rem a b in
  if r <> 0L && ((r < 0L) <> (b < 0L)) then Int64.pred q else q

let floor_mod64 a b =
  let r = Int64.rem a b in
  if r <> 0L && ((r < 0L) <> (b < 0L)) then Int64.add r b else r

let floor_div_i a b =
  let q = a / b and r = a mod b in
  if r <> 0 && ((r < 0) <> (b < 0)) then q - 1 else q

let floor_mod_i a b =
  let r = a mod b in
  if r <> 0 && ((r < 0) <> (b < 0)) then r + b else r

(* days since 1970-01-01 UTC *)
let days_from_civil y mo d =
  let y' = if mo <= 2 then y - 1 else y in
  let era = floor_div_i (if y' >= 0 then y' else y' - 399) 400 in
  let yoe = y' - (era * 400) in
  let doy = (((153 * (if mo > 2 then mo - 3 else mo + 9)) + 2) / 5) + d - 1 in
  let doe = (yoe * 365) + (yoe / 4) - (yoe / 100) + doy in
  (era * 146097) + doe - 719468

(* inverse: (year, month, day) of days since epoch *)
let civil_from_days (z : int) =
  let z = z + 719468 in
  let era = floor_div_i (if z >= 0 then z else z - 146096) 146097 in
  let doe = z - (era * 146097) in
  let yoe = (doe - (doe / 1460) + (doe / 36524) - (doe / 146096)) / 365 in
  let y = yoe + (era * 400) in
  let doy = doe - ((365 * yoe) + (yoe / 4) - (yoe / 100)) in
  let mp = ((5 * doy) + 2) / 153 in
  let d = doy - (((153 * mp) + 2) / 5) + 1 in
  let m = if mp < 10 then mp + 3 else mp - 9 in
  ((if m <= 2 then y + 1 else y), m, d)

let days_in_month year month =
  match month with
  | 1 | 3 | 5 | 7 | 8 | 10 | 12 -> 31
  | 4 | 6 | 9 | 11 -> 30
  | 2 ->
      if (year mod 4 = 0 && year mod 100 <> 0) || year mod 400 = 0 then 29
      else 28
  | _ -> invalid_arg "month out of range"

(* civil fields of an epoch-ms instant read at a fixed minute offset
   (pure arithmetic — no tz table) *)
let civil_at_offset off_min (ms : int64) : civil =
  let shifted = Int64.add ms (Int64.of_int (off_min * 60000)) in
  let secs = floor_div64 shifted 1000L in
  let ms_part = Int64.to_int (floor_mod64 shifted 1000L) in
  let days = floor_div64 secs 86400L in
  let day_secs = Int64.to_int (floor_mod64 secs 86400L) in
  let y, mo, d = civil_from_days (Int64.to_int days) in
  { cv_year = y
  ; cv_month = mo
  ; cv_day = d
  ; cv_hour = day_secs / 3600
  ; cv_minute = (day_secs mod 3600) / 60
  ; cv_second = day_secs mod 60
  ; cv_ms = ms_part
  }

(* epoch ms of a civil time at a fixed minute offset. Field rollover
   follows js/Date semantics: month spills into year, day spills into
   adjacent months, smaller fields just add. *)
let epoch_ms_at_offset off_min c : int64 =
  let total_months = (c.cv_year * 12) + (c.cv_month - 1) in
  let y' = floor_div_i total_months 12 in
  let m' = floor_mod_i total_months 12 + 1 in
  let days = days_from_civil y' m' 1 + (c.cv_day - 1) in
  Int64.sub
    (Int64.add
       (Int64.mul
          (Int64.of_int
             ((days * 86400) + (c.cv_hour * 3600) + (c.cv_minute * 60)
              + c.cv_second))
          1000L)
       (Int64.of_int c.cv_ms))
    (Int64.of_int (off_min * 60000))

let civil_of_unix_tm tm ms_part =
  { cv_year = tm.Unix.tm_year + 1900
  ; cv_month = tm.Unix.tm_mon + 1
  ; cv_day = tm.Unix.tm_mday
  ; cv_hour = tm.Unix.tm_hour
  ; cv_minute = tm.Unix.tm_min
  ; cv_second = tm.Unix.tm_sec
  ; cv_ms = ms_part
  }

(* ---- civil ---- *)

let civil ~year ~month ~day ~hour ~minute ~second ~ms =
  { cv_year = year; cv_month = month; cv_day = day; cv_hour = hour;
    cv_minute = minute; cv_second = second; cv_ms = ms }

let civil_fields c =
  ( c.cv_year, c.cv_month, c.cv_day, c.cv_hour, c.cv_minute, c.cv_second,
    c.cv_ms )

let compare_civil a b = compare (civil_fields a) (civil_fields b)

(* win32unix localtime/mktime raise EINVAL on instants that map before
   1970-01-01; for those out-of-range inputs the local offset at the
   epoch stands in so both directions still invert. *)
let epoch_tz_offset_minutes : int option ref = ref None

let epoch_tz_offset_minutes () =
  match !epoch_tz_offset_minutes with
  | Some off -> off
  | None ->
      (* mktime reads tm fields as local civil, so its value at an
         instant is instant-minus-offset. Probe after the epoch: east
         of UTC a probe at 0 maps to a negative local value, which
         win32 mktime rejects. *)
      let probe = 172800. in
      let secs, _ = Unix.mktime (Unix.gmtime probe) in
      let off = int_of_float ((probe -. secs) /. 60.) in
      epoch_tz_offset_minutes := Some off;
      off

let civil_of_epoch_ms tz ms =
  match tz with
  | Local_tz ->
      (* floor, not truncation: the civil second containing a negative
         epoch-ms is its floor (ms part is taken floor-mod below) *)
      let secs = Float.floor (Int64.to_float ms /. 1000.) in
      (match
         (try `Local (Unix.localtime secs)
          with Unix.Unix_error (Unix.EINVAL, _, _) -> `Fallback)
       with
       | `Local tm ->
           civil_of_unix_tm
             tm
             (Int64.(to_int (rem (add (rem ms 1000L) 1000L) 1000L)))
       | `Fallback -> civil_at_offset (epoch_tz_offset_minutes ()) ms)
  | Offset_tz off -> civil_at_offset off ms

let epoch_ms_of_civil tz c =
  match tz with
  | Local_tz ->
      (* mktime normalizes out-of-range fields like js/Date setters *)
      let tm =
        { Unix.tm_sec = c.cv_second
        ; tm_min = c.cv_minute
        ; tm_hour = c.cv_hour
        ; tm_mday = c.cv_day
        ; tm_mon = c.cv_month - 1
        ; tm_year = c.cv_year - 1900
        ; tm_wday = 0
        ; tm_yday = 0
        ; tm_isdst = false
        }
      in
      (match
         (try `Mk (Unix.mktime tm)
          with Unix.Unix_error (Unix.EINVAL, _, _) -> `Fallback)
       with
       | `Mk (secs, _) ->
           Int64.of_float (secs *. 1000. +. float_of_int c.cv_ms)
       | `Fallback -> epoch_ms_at_offset (epoch_tz_offset_minutes ()) c)
  | Offset_tz off -> epoch_ms_at_offset off c

(* ---- local_date ---- *)

let local_date ~year ~month ~day ~tz =
  if month < 1 || month > 12 then None
  else if day < 1 || day > days_in_month year month then None
  else Some { ld_year = year; ld_month = month; ld_day = day; ld_tz = tz }

let local_date_fields d = (d.ld_year, d.ld_month, d.ld_day)
let local_date_tz d = d.ld_tz

let compare_local_date a b =
  compare (local_date_fields a) (local_date_fields b)

let equal_local_date a b =
  local_date_fields a = local_date_fields b && equal_tz a.ld_tz b.ld_tz

(* ---- journal-day int (yyyymmdd) ---- *)

let journal_day_of_local_date d =
  (d.ld_year * 10000) + (d.ld_month * 100) + d.ld_day

let local_date_of_journal_day tz n =
  local_date ~year:(n / 10000) ~month:((n / 100) mod 100) ~day:(n mod 100) ~tz

(* ---- ISO-8601 ---- *)

let iso_string_of_epoch_ms ms =
  let c = civil_at_offset 0 ms in
  Printf.sprintf "%04d-%02d-%02dT%02d:%02d:%02d.%03dZ" c.cv_year
    c.cv_month c.cv_day c.cv_hour c.cv_minute c.cv_second c.cv_ms

(* ISO 8601 "YYYY-MM-DD[T ]HH:MM[:SS[.fff]][Z|±HH:MM|±HHMM]" — covers the
   ~t/#inst forms; native does not emulate the rest of js/Date.parse. *)
let epoch_ms_of_iso_string s : epoch_ms option =
  let n = String.length s in
  let digit i = i < n && s.[i] >= '0' && s.[i] <= '9' in
  let uint i len =
    if i + len <= n && String.for_all (fun c -> c >= '0' && c <= '9')
         (String.sub s i len)
    then Some (int_of_string (String.sub s i len))
    else None
  in
  let skip_digits i =
    let rec go j = if j < n && digit j then go (j + 1) else j in
    go i
  in
  match (uint 0 4, n > 4 && s.[4] = '-', n > 7 && s.[7] = '-') with
  | Some year, true, true -> (
      match (uint 5 2, uint 8 2) with
      | Some month, Some day ->
          let i = 10 in
          (* optional time part after 'T' or space *)
          let time, i =
            if i < n && (s.[i] = 'T' || s.[i] = ' ') then
              let i = i + 1 in
              match (uint i 2, i + 2 < n && s.[i + 2] = ':', uint (i + 3) 2) with
              | Some hour, true, Some minute ->
                  let i = i + 5 in
                  let second, i =
                    if i < n && s.[i] = ':' then
                      match uint (i + 1) 2 with
                      | Some sec -> (sec, i + 3)
                      | None -> (0, i)
                    else (0, i)
                  in
                  let ms_part, i =
                    if i < n && s.[i] = '.' then
                      let stop = min (skip_digits (i + 1)) (i + 4) in
                      if stop > i + 1 then
                        ( int_of_string
                            (String.sub s (i + 1) (stop - i - 1)
                             ^ String.make (3 - (stop - i - 1)) '0')
                        , stop )
                      else (0, i)
                    else (0, i)
                  in
                  (Some (hour, minute, second, ms_part), i)
              | _ -> (None, i)
            else (None, i)
          in
          (* optional tz suffix: 'Z' or ±HH[:MM|MM] *)
          let offset_min, ok =
            let rec scan i =
              if i >= n then (0, true)
              else
                match s.[i] with
                | 'Z' | 'z' -> (0, true)
                | '+' | '-' ->
                    let sign = if s.[i] = '-' then -1 else 1 in
                    let j = skip_digits (i + 1) in
                    let raw =
                      try int_of_string (String.sub s (i + 1) (j - i - 1))
                      with _ -> 0
                    in
                    if j < n && s.[j] = ':' then
                      let j2 = skip_digits (j + 1) in
                      let mm =
                        try int_of_string (String.sub s (j + 1) (j2 - j - 1))
                        with _ -> 0
                      in
                      (sign * ((raw * 60) + mm), true)
                    else if j - i - 1 >= 4 then
                      (sign * (((raw / 100) * 60) + (raw mod 100)), true)
                    else (sign * raw * 60, true)
                | _ -> scan (i + 1)
            in
            scan i
          in
          let hour, minute, second, ms_part =
            match time with
            | Some (h, mi, sec, ms') -> (h, mi, sec, ms')
            | None -> (0, 0, 0, 0)
          in
          if ok && month >= 1 && month <= 12 && day >= 1
             && day <= days_in_month year month && hour <= 23
             && minute <= 59 && second <= 59
          then
            Some
              (epoch_ms_at_offset offset_min
                 { cv_year = year; cv_month = month; cv_day = day;
                   cv_hour = hour; cv_minute = minute; cv_second = second;
                   cv_ms = ms_part })
          else None
      | _ -> None)
  | _ -> None

end

module Unicode = struct
(* UTF-8 codec (scalar values as ints). *)
let decode_utf8 (s : string) : int list =
  let len = String.length s in
  let byte i = Char.code (String.get s i) in
  let rec loop i acc =
    if i >= len then List.rev acc
    else
      let b0 = byte i in
      if b0 < 0x80 then loop (i + 1) (b0 :: acc)
      else if b0 < 0xC0 then loop (i + 1) (0xFFFD :: acc)
      else if b0 < 0xE0 && i + 1 < len then
        loop (i + 2) (((b0 land 0x1F) lsl 6 lor (byte (i + 1) land 0x3F)) :: acc)
      else if b0 < 0xF0 && i + 2 < len then
        loop (i + 3)
          (((b0 land 0x0F) lsl 12 lor ((byte (i + 1) land 0x3F) lsl 6)
            lor (byte (i + 2) land 0x3F))
          :: acc)
      else if i + 3 < len then
        loop (i + 4)
          (((b0 land 0x07) lsl 18 lor ((byte (i + 1) land 0x3F) lsl 12)
            lor ((byte (i + 2) land 0x3F) lsl 6)
            lor (byte (i + 3) land 0x3F))
          :: acc)
      else acc |> List.rev
  in
  loop 0 []

let encode_utf8 (cps : int list) : string =
  let buf = Buffer.create 64 in
  let add c = Buffer.add_char buf (Char.chr c) in
  List.iter
    (fun cp ->
       if cp < 0x80 then add cp
       else if cp < 0x800 then begin
         add (0xC0 lor (cp lsr 6));
         add (0x80 lor (cp land 0x3F))
       end
       else if cp < 0x10000 then begin
         add (0xE0 lor (cp lsr 12));
         add (0x80 lor ((cp lsr 6) land 0x3F));
         add (0x80 lor (cp land 0x3F))
       end
       else begin
         add (0xF0 lor (cp lsr 18));
         add (0x80 lor ((cp lsr 12) land 0x3F));
         add (0x80 lor ((cp lsr 6) land 0x3F));
         add (0x80 lor (cp land 0x3F))
       end)
    cps;
  Buffer.contents buf

(* String.prototype.toLowerCase — per-codepoint full simple case mapping. *)
let lowercase (s : string) : string =
  let scalars = Array.of_list (decode_utf8 s) in
  let cased_after = Array.make (Array.length scalars) false in
  let following = ref false in
  for index = Array.length scalars - 1 downto 0 do
    cased_after.(index) <- !following;
    let value = Uchar.unsafe_of_int scalars.(index) in
    if not (Uucp.Case.is_case_ignorable value) then following := Uucp.Case.is_cased value
  done;
  let output = Buffer.create (String.length s) and preceding = ref false in
  Array.iteri (fun index cp ->
    let value = Uchar.unsafe_of_int cp in
    (* JavaScript's default lowercase includes the contextual Final_Sigma rule. *)
    if cp = 0x03A3 && !preceding && not cased_after.(index) then Buffer.add_utf_8_uchar output (Uchar.of_int 0x03C2)
    else (match Uucp.Case.Map.to_lower value with
      | `Self -> Buffer.add_utf_8_uchar output value
      | `Uchars values -> List.iter (Buffer.add_utf_8_uchar output) values);
    if not (Uucp.Case.is_case_ignorable value) then preceding := Uucp.Case.is_cased value) scalars;
  Buffer.contents output

(* String.prototype.toUpperCase — per-codepoint full simple case mapping. *)
let uppercase (s : string) : string =
  decode_utf8 s
  |> List.concat_map (fun cp ->
         match Uucp.Case.Map.to_upper (Uchar.unsafe_of_int cp) with
         | `Self -> [ cp ]
         | `Uchars us -> List.map Uchar.to_int us)
  |> encode_utf8

(* ECMAScript WhiteSpace + LineTerminator code points. *)
let is_js_whitespace cp =
  match cp with
  | 0x0009 | 0x000A | 0x000B | 0x000C | 0x000D | 0x0020 | 0x00A0
  | 0x1680 | 0x2028 | 0x2029 | 0x202F | 0x205F | 0x3000 | 0xFEFF -> true
  | _ -> cp >= 0x2000 && cp <= 0x200A

(* List.drop_while is OCaml >= 5.3; this tree still builds on 5.1 *)
let rec drop_while_js_ws cps =
  match cps with
  | cp :: rest when is_js_whitespace cp -> drop_while_js_ws rest
  | _ -> cps

let trim (s : string) : string =
  match decode_utf8 s with
  | [] -> ""
  | cps ->
      let cps = List.rev (drop_while_js_ws (List.rev (drop_while_js_ws cps))) in
      encode_utf8 cps

let triml (s : string) : string =
  encode_utf8 (drop_while_js_ws (decode_utf8 s))

let trimr (s : string) : string =
  encode_utf8 (List.rev (drop_while_js_ws (List.rev (decode_utf8 s))))

let case_map_cp map cp =
  match map (Uchar.unsafe_of_int cp) with
  | `Self -> [ cp ]
  | `Uchars us -> List.map Uchar.to_int us

let capitalize (s : string) : string =
  match decode_utf8 s with
  | [] -> ""
  | c :: rest ->
      encode_utf8
        (case_map_cp Uucp.Case.Map.to_upper c
         @ List.concat_map (case_map_cp Uucp.Case.Map.to_lower) rest)

(* String.length — UTF-16 code units: BMP 1, astral 2. *)
let js_length (s : string) : int =
  List.fold_left
    (fun acc cp -> acc + (if cp > 0xFFFF then 2 else 1))
    0 (decode_utf8 s)

let utf16_units s =
  decode_utf8 s
  |> List.concat_map (fun cp ->
         if cp <= 0xFFFF then [ cp ]
         else
           let cp = cp - 0x10000 in
           [ 0xD800 lor (cp lsr 10); 0xDC00 lor (cp land 0x3FF) ])
  |> Array.of_list

let of_utf16_units units =
  let n = Array.length units in
  let rec decode i acc =
    if i >= n then encode_utf8 (List.rev acc)
    else
      let u = units.(i) in
      if u >= 0xD800 && u <= 0xDBFF && i + 1 < n
         && units.(i + 1) >= 0xDC00 && units.(i + 1) <= 0xDFFF then
        let cp = 0x10000 + ((u - 0xD800) lsl 10) + (units.(i + 1) - 0xDC00) in
        decode (i + 2) (cp :: acc)
      else
        decode (i + 1) ((if u >= 0xD800 && u <= 0xDFFF then 0xFFFD else u) :: acc)
  in
  decode 0 []

(* subs on UTF-16 units — a boundary inside an astral char keeps/drops
   the whole char (a lone surrogate is not encodable). *)
let js_sub (s : string) (start : int) (end_ : int) : string =
  let rec skip cps pos units =
    match cps with
    | [] -> cps, units
    | c :: rest ->
        let w = if c > 0xFFFF then 2 else 1 in
        if units + w > pos then cps, units else skip rest pos (units + w)
  in
  let cps = decode_utf8 s in
  let cps, u0 = skip cps start 0 in
  let rec take cps rem acc =
    match cps with
    | [] -> List.rev acc
    | c :: rest ->
        let w = if c > 0xFFFF then 2 else 1 in
        if w > rem then List.rev acc else take rest (rem - w) (c :: acc)
  in
  encode_utf8 (take cps (end_ - u0) [])

end

module Regexp = struct
type t = Re.re

type re_match =
  { groups : string option array
  ; offset : int
  ; last : int }

(* JS \uXXXX escape -> literal UTF-8 bytes (Re.Pcre classes do not
   support \x escapes). Regex metacharacters stay backslash-escaped so
   they keep their literal meaning in both contexts. *)
let translate s =
  let n = String.length s in
  let b = Buffer.create n in
  let is_hex c =
    (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F')
  in
  let hex_val i =
    let d c =
      if c >= '0' && c <= '9' then Char.code c - Char.code '0'
      else if c >= 'a' && c <= 'f' then Char.code c - Char.code 'a' + 10
      else Char.code c - Char.code 'A' + 10
    in
    (d s.[i] lsl 12) + (d s.[i + 1] lsl 8) + (d s.[i + 2] lsl 4) + d s.[i + 3]
  in
  let add_codepoint cp =
    if cp < 0x80 then begin
      let c = Char.chr cp in
      if String.contains "[]\\^$.|?*+(){}" c then Buffer.add_char b '\\';
      Buffer.add_char b c
    end else begin
      (* UTF-8 encode *)
      if cp < 0x800 then begin
        Buffer.add_char b (Char.chr (0xC0 lor (cp lsr 6)));
        Buffer.add_char b (Char.chr (0x80 lor (cp land 0x3F)))
      end else if cp < 0x10000 then begin
        Buffer.add_char b (Char.chr (0xE0 lor (cp lsr 12)));
        Buffer.add_char b (Char.chr (0x80 lor ((cp lsr 6) land 0x3F)));
        Buffer.add_char b (Char.chr (0x80 lor (cp land 0x3F)))
      end else begin
        Buffer.add_char b (Char.chr (0xF0 lor (cp lsr 18)));
        Buffer.add_char b (Char.chr (0x80 lor ((cp lsr 12) land 0x3F)));
        Buffer.add_char b (Char.chr (0x80 lor ((cp lsr 6) land 0x3F)));
        Buffer.add_char b (Char.chr (0x80 lor (cp land 0x3F)))
      end
    end
  in
  let rec loop i =
    if i < n then begin
      if
        s.[i] = '\\' && i + 5 < n
        && s.[i + 1] = 'u'
        && is_hex s.[i + 2] && is_hex s.[i + 3] && is_hex s.[i + 4]
        && is_hex s.[i + 5]
      then begin
        add_codepoint (hex_val (i + 2));
        loop (i + 6)
      end else begin
        Buffer.add_char b s.[i];
        loop (i + 1)
      end
    end
  in
  loop 0;
  Buffer.contents b

(* cljs re-pattern is case-sensitive; (?i) maps to CASELESS. *)
let compile ?(caseless = false) s =
  Re.compile
    (Re.Pcre.re ~flags:(if caseless then [ `CASELESS ] else []) (translate s))

let test t s = Re.execp t s

let re_match_of_group g =
  let offset, last = Re.Group.offset g 0 in
  { groups = Array.init (Re.Group.nb_groups g) (Re.Group.get_opt g)
  ; offset
  ; last }

let exec ?(pos = 0) t s =
  Option.map re_match_of_group (Re.exec_opt ~pos t s)

let replace t ~f s =
  match Re.exec_opt t s with
  | None -> s
  | Some g ->
      let match_ = Re.Group.get g 0 in
      let nb = Re.Group.nb_groups g in
      let groups = Array.init nb (fun i -> Re.Group.get_opt g i) in
      let offset, stop = Re.Group.offset g 0 in
      let rep = f ~match_ ~groups ~offset ~input:s in
      String.sub s 0 offset
      ^ rep
      ^ String.sub s stop (String.length s - stop)

let replace_all t ~f s =
  let b = Buffer.create (String.length s) in
  let rec loop pos =
    match Re.exec_opt ~pos t s with
    | None -> Buffer.add_string b (String.sub s pos (String.length s - pos))
    | Some g ->
        let m = re_match_of_group g in
        let match_ =
          match m.groups with [||] -> "" | xs -> Option.value ~default:"" xs.(0)
        in
        Buffer.add_string b (String.sub s pos (m.offset - pos));
        Buffer.add_string b (f ~match_ ~groups:m.groups ~offset:m.offset ~input:s);
        (* empty match: emit one char and advance, as JS /g does *)
        if m.last = m.offset && m.last < String.length s then begin
          Buffer.add_char b s.[m.last];
          loop (m.last + 1)
        end else if m.last > m.offset then loop m.last
  in
  loop 0;
  Buffer.contents b

end

