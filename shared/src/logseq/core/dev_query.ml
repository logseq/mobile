let parse_long ?(radix = 0) (s0 : string) : int option =
  let n0 = String.length s0 in
  let i0 = ref 0 in
  while
    !i0 < n0
    && (match s0.[!i0] with
        | ' ' | '\t' | '\n' | '\r' | '\011' | '\012' -> true
        | _ -> false)
