                       (c >= '0' && c <= '9')
                       || (c >= 'a' && c <= 'f')
                       || (c >= 'A' && c <= 'F')
                   | 8 -> c >= '0' && c <= '7'
                   | _ -> c = '0' || c = '1')
                 s
