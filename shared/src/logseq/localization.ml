let resolve language system_language =
  let value = if language = "system" then system_language else language in
  let value = String.lowercase_ascii (String.map (fun c -> if c = '_' then '-' else c) value) in
  let exact = List.find_opt (fun (key, _) -> String.lowercase_ascii key = value) dictionaries in
  match exact with
  | Some (key, _) -> key
  | None when String.starts_with ~prefix:"zh" value ->
    if List.exists (fun part -> List.mem part ["hant"; "tw"; "hk"; "mo"]) (String.split_on_char '-' value)
    then "zh-Hant" else "zh-CN"
  | None -> let primary = List.hd (String.split_on_char '-' value) in
    if List.mem_assoc primary dictionaries then primary else "en"

let translate ~language ~system_language source =
  let locale = String.lowercase_ascii (resolve language system_language) in
  List.find_map (fun (key, entries) ->
    if String.lowercase_ascii key = locale then List.assoc_opt source entries else None)
    dictionaries
  |> Option.value ~default:source
