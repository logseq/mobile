// Android hardware-back routing, mirroring the former PopScope semantics:
// composer dismissal takes precedence, then nav-stack back, then the
// system.
@Composable
private fun NavigationBoundary(context: LuiExtensionContext) {
    val depth = context.int("depth") ?: 0
    // back-depth adds one more level for transient shell state (editing,
    // selection, non-journal panes) that back settles without popping a
    // route; count=0 asks the core to settle instead of popping.
    val backDepth = context.int("back-depth") ?: depth
    val dismissesComposer = context.flag("composer-dismissal-enabled")
    val occupies = context.flag("bottom-occupies-layout-space")
    BackHandler(enabled = backDepth > 0 || dismissesComposer) {
        if (dismissesComposer) {
            context.emit("dismiss-composer")
        } else if (backDepth > depth) {
            context.emit("back", "count" to 0)
        } else if (depth > 0) {
            context.emit("back", "count" to 1)
        }
    }
    var journalTitle by remember { mutableStateOf<String?>(null) }
    BoxWithConstraints(Modifier.fillMaxSize()) {
        val width = maxWidth.value.toInt()
        LaunchedEffect(width) { context.emit("viewport-changed", "width" to width) }
        CompositionLocalProvider(
            dev.lui.LocalLuiSectionTitle provides journalTitle,
            dev.lui.LocalLuiSectionTitleChanged provides { journalTitle = it },
        ) {
            val childIds = context.children
            if (childIds.size == 2) {
                // Second child is the bottom chrome. Hoist it out of the content
                // column like iOS's safeAreaInset/overlay so the composer's
                // internal `grow` props can't starve the journal; intrinsic
                // sizing keeps it at natural height instead of letting those
                // props claim the whole screen.
                if (occupies) {
                    Column(Modifier.fillMaxSize()) {
                        Box(Modifier.weight(1f)) { NavigationContent(context, childIds[0], dismissesComposer) }
                        Box(Modifier.height(IntrinsicSize.Min)) {
                            context.child(childIds[1])
                        }
                    }
                } else {
                    Box(Modifier.fillMaxSize()) {
                        Column(Modifier.fillMaxSize()) { NavigationContent(context, childIds[0], dismissesComposer) }
                        Box(
                            Modifier
                                .align(Alignment.BottomCenter)
                                .height(IntrinsicSize.Min),
                        ) {
                            context.child(childIds[1])
                        }
                    }
                }
            } else {
                context.Children()
            }
        }
    }
}

@Composable
private fun NavigationContent(context: LuiExtensionContext, contentId: Long, dismissesComposer: Boolean) {
    val focus = LocalFocusManager.current
    val keyboard = LocalSoftwareKeyboardController.current
    Box(Modifier.fillMaxSize()) {
        context.child(contentId)
        if (dismissesComposer) {
            Box(Modifier.fillMaxSize()
                .testTag("surface.composer.dismiss")
                .clickable(
                    interactionSource = remember { MutableInteractionSource() },
                    indication = null,
                    onClickLabel = "Dismiss composer",
                ) {
                    focus.clearFocus()
                    keyboard?.hide()
                    context.emit("dismiss-composer")
                })
        }
    }
}

// Search owns the content area and bottom controls while retaining the app below it.
@OptIn(androidx.compose.material3.ExperimentalMaterial3Api::class)
@Composable
private fun SearchPresentation(context: LuiExtensionContext) {
    if (!context.flag("presented")) {
        context.Children()
        return
    }
    val title = context.string("title").orEmpty().ifEmpty { "Search" }
    val query = context.string("query").orEmpty()
    val depth = context.int("depth") ?: 0
    val focusRequester = remember { FocusRequester() }
    val keyboard = LocalSoftwareKeyboardController.current
    LaunchedEffect(depth) {
        if (depth == 0) {
            focusRequester.requestFocus()
            keyboard?.show()
        } else keyboard?.hide()
    }
    DisposableEffect(Unit) { onDispose { keyboard?.hide() } }
    BackHandler {
        if (depth > 0) context.emit("back", "count" to 1) else context.emit("dismiss")
    }
    Surface(modifier = Modifier.fillMaxSize().testTag("native-search-presentation"),
        color = MaterialTheme.colorScheme.background) {
        Column {
            if (depth > 0) {
                androidx.compose.material3.TopAppBar(
                    title = { Text(title, maxLines = 1) },
                    navigationIcon = {
                        IconButton(onClick = { context.emit("back", "count" to 1) },
                            modifier = Modifier.testTag("button.search.back")) {
                            Icon(androidx.compose.material.icons.Icons.AutoMirrored.Filled.ArrowBack, context.string("back-title") ?: "Back")
                        }
                    },
                    actions = {
                        context.children.getOrNull(1)?.let { context.child(it) }
                        IconButton(onClick = { context.emit("dismiss") }) {
                            Icon(Icons.Filled.Close, context.string("close-title") ?: "Close search")
                        }
                    },
                )
            }
            Box(Modifier.weight(1f)) { context.children.firstOrNull()?.let { context.child(it) } }
            if (depth == 0) {
                Row(Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 8.dp),
                    verticalAlignment = Alignment.CenterVertically) {
                    var fieldValue by remember(query) { mutableStateOf(query) }
                    androidx.compose.material3.OutlinedTextField(
                        value = fieldValue,
                        onValueChange = { fieldValue = it; context.emit("query-changed", "query" to it) },
                        modifier = Modifier.weight(1f).focusRequester(focusRequester).testTag("field.search"),
                        shape = MaterialTheme.shapes.small,
                        textStyle = MaterialTheme.typography.bodyLarge,
                        placeholder = { Text(title) },
                        leadingIcon = { Icon(Icons.Filled.Search, contentDescription = null) },
                        trailingIcon = if (fieldValue.isEmpty()) null else ({
                            IconButton(onClick = { fieldValue = ""; context.emit("query-changed", "query" to "") }) {
                                Icon(Icons.Filled.Close, context.string("clear-title") ?: "Clear")
                            }
                        }),
                        singleLine = true,
                    )
                    IconButton(onClick = { context.emit("dismiss") },
                        modifier = Modifier.size(48.dp).testTag("button.search.close")) {
                        Icon(Icons.Filled.Close, context.string("close-title") ?: "Close search")
                    }
                }
            }
        }
    }
}
